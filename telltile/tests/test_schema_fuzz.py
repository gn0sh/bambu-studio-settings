    def test_range_bounds(self):
        """Each bound is accepted and one step past it is refused, for every setting, as a string and a number."""
        for block, rules in R.RULES.items():
            for k, rule in rules.items():
                path = ("filaments", 0, "tuned", "P1S", block, k, "value")

def ptext(path):
    out = ""
    for k in path:
        out += "[%d]" % k if isinstance(k, int) else ("." if out else "") + k
    return out or "(top)"


def g(x):
    return "%g" % x


def rule_sample(rule):
    if "enum" in rule:
        return rule["enum"][0]
    if "bool" in rule:
        return "1"
    for kind in ("int", "num"):
        if kind in rule:
            return g(rule[kind][0])
    return g(rule["pct"][0]) + "%"


def build(node, full=True):
    """A valid value for node: every optional key and one entry per map and list (full), or the least (minimal)."""
    kind = node[0]
    if kind == "obj":
        keys = list(node[1]) + (list(node[2]) if full else [])
        return {k: build(node[1].get(k) or node[2][k], full) for k in keys}
    if kind == "map":
        return {SAMPLE[node[1][1]]: build(node[2], full)} if full else {}
    if kind == "list":
        return [build(node[1], full)] if full else []
    if kind == "set":
        return {k: build(sub, full) for k, sub in node[2].items()} if full else {}
    if kind == "text":
        return "text" if full else ""
    if kind == "re":
        return (SAMPLE if full else MINIMAL)[node[1]]
    if kind in ("const", "enum"):
        return node[1] if kind == "const" else node[1][0]
    if kind == "bool":
        return False
    return rule_sample(node[2])


def positions(node, value, path=()):
    """(path, node, value) for every value in a document built from node, depth first."""
    yield path, node, value
    kind = node[0]
    if kind == "obj":
        for k, x in value.items():
            for p in positions(node[1].get(k) or node[2][k], x, path + (k,)):
                yield p
    elif kind == "map":
        for k, x in value.items():
            for p in positions(node[2], x, path + (k,)):
                yield p
    elif kind == "list":
        for i, x in enumerate(value):
            for p in positions(node[1], x, path + (i,)):
                yield p
    elif kind == "set":
        for k, x in value.items():
            for p in positions(node[2][k], x, path + (k,)):
                yield p


def accepts_type(node, v):
    kind = node[0]
    if isinstance(v, bool):
        return kind == "bool"
    if kind in ("text", "re", "const"):
        return isinstance(v, str)
    if kind == "enum":
        return any(type(v) is type(x) for x in node[1])
    if kind in ("obj", "map", "set"):
        return isinstance(v, dict)
    if kind == "list":
        return isinstance(v, list)
    if kind == "value":
        rule = node[2]
        return isinstance(v, str) or (isinstance(v, (int, float)) and any(k in rule for k in ("int", "num", "bool")))
    return False


def bound_cases(rule):
    """(value, accepted) at each range bound and one step past it, as strings and (where allowed) JSON numbers."""
    out = []
    if "int" in rule:
        lo, hi = rule["int"]
        out += [(lo, True), (hi, True), (lo - 1, False), (hi + 1, False)]
        out += [(str(x), ok) for x, ok in out]
        out += [(float(lo), False)]                                    # an int setting is not 165.0
    if "num" in rule:
        lo, hi = rule["num"]
        step = 0.00001
        nums = [(lo, True), (hi, True), (round(lo - step, 5), False), (round(hi + step, 5), False)]
        out += nums + [("%.5f" % x, ok) for x, ok in nums]
    if "pct" in rule:
        lo, hi = rule["pct"]
        out += [("%g%%" % x, ok) for x, ok in ((lo, True), (hi, True), (round(lo - 0.01, 2), False),
                                               (round(hi + 0.01, 2), False))]
        if "num" not in rule:
            out += [(lo, False), (g(lo), False)]                       # a percent needs its "%"
    if "bool" in rule:
        out += [(0, True), (1, True), ("0", True), ("1", True), (2, False), ("2", False), (True, False),
                ("true", False), (-1, False)]
    if "enum" in rule:
        out += [(x, True) for x in rule["enum"]] + [("zz-not-an-option", False), (rule["enum"][0].upper() + "X", False)]
    out += [("nil", rule["nil"]), (float("nan"), False), (float("inf"), False), ("1e3", False), (" 1", False)]
    return out


class Case(object):
    """One hostile edit of the full registry: set (path, value), add a key, or rename a key; `where` is the path
    the refusal must name. A value may be a function that builds it (Lazy): the 10 000-deep lists are built only
    while their case is applied, so the case list holds no millions of objects (it did: 3.6 M, and every full
    garbage collection then took 2 s inside whichever timed call it fell in, on Python 3.8 and 3.13 alike)."""
    def __init__(self, label, op, path, value=None, where=None, newkey=None):
        self.label, self.op, self.path, self.value, self.newkey = label, op, path, value, newkey
        self.where = ptext(path if where is None else where)

    @contextlib.contextmanager
    def applied(self, doc):
        parent = doc
        for k in self.path[:-1] if self.op != "add" else self.path:
            parent = parent[k]
        value = self.value() if isinstance(self.value, Lazy) else self.value
        if self.op == "set":
            k = self.path[-1]; old = parent[k]; parent[k] = value
            try:
                yield doc
            finally:
                parent[k] = old
        elif self.op == "add":
            parent[self.newkey] = value
            try:
                yield doc
            finally:
                del parent[self.newkey]
        else:                                                          # rename the key at path[-1] to newkey
            k = self.path[-1]; items = list(parent.items()); parent.clear()
            parent.update((self.newkey if a == k else a, b) for a, b in items)
            try:
                yield doc
            finally:
                parent.clear(); parent.update(items)


class Lazy(object):
    """A case value built on demand (see Case)."""
    def __init__(self, fn):
        self.fn = fn

    def __call__(self):
        return self.fn()


def nested(v, depth):
    for _ in range(depth):
        v = [v]
    return v


def generate(doc):
    cases = []
    for path, node, value in positions(R.SCHEMA, doc):
        kind = node[0]
        here = ptext(path)
        if path:
            for v in ({"a": 1}, [1], "x", 7, 1.5, True, None):
                if not accepts_type(node, v):
                    cases.append(Case("%s <- %s" % (here, R._json_type(v)), "set", path, v))
            cases.append(Case("%s in 10 000 lists" % here, "set", path, Lazy(lambda v=value: nested(v, 10000)),
                              where=path + (0,) if kind == "list" else path))
        if kind in ("text", "re"):
            n = node[1] if kind == "text" else node[2]
            for v in ("A" * (n + 1), "A" * MB):
                cases.append(Case("%s %d chars" % (here, len(v)), "set", path, v))
        if kind == "text":
            for ch in ("\x1b", "\x07", "\x9b", "‮", " ", "\x00"):
                cases.append(Case("%s control %r" % (here, ch), "set", path, "ok" + ch))
        if kind == "re" and node[1] in QUOTED:
            for ch in SHELL_CHARS:
                cases.append(Case("%s + %r" % (here, ch), "set", path, value + ch))
                cases.append(Case("%s %r inside" % (here, ch), "set", path, value[:1] + ch + value[1:]))
            cases.append(Case("%s leading -" % here, "set", path, "-" + value))
        if kind == "re" and node[1] is not R.DATE_OR_EMPTY_RE:
            cases.append(Case("%s empty" % here, "set", path, ""))
        if kind == "enum":
            off = "zz" if isinstance(node[1][0], str) else node[1][0] + 0.5
            cases.append(Case("%s off-enum" % here, "set", path, off))
        if kind == "const":
            cases.append(Case("%s other schema" % here, "set", path, node[1] + " v2"))
        if kind == "value":
            for v, ok in bound_cases(node[2]):
                if not ok:
                    cases.append(Case("%s = %r" % (here, v), "set", path, v))
            for v in ("9" * 33, "9" * MB):
                cases.append(Case("%s %d chars" % (here, len(v)), "set", path, v))
        if kind == "obj":
            cases.append(Case("%s unknown key" % here, "add", path, "x", where=path, newkey="zz_unknown"))
            for k in node[1]:
                stripped = dict((a, b) for a, b in value.items() if a != k)
                cases.append(Case("%s missing %s" % (here, k), "set", path, stripped) if path else None)
        if kind == "map":
            keynode = node[1]
            for k in list(value)[:1]:
                bad_keys = ["", "A" * (keynode[2] + 1), "A" * MB, "bad key!"]
                if keynode[1] in QUOTED:
                    bad_keys += [k + ch for ch in SHELL_CHARS] + ["-" + k]
                for nk in bad_keys:
                    cases.append(Case("%s key %r" % (here, nk[:40]), "rename", path + (k,), where=path, newkey=nk))
            over = dict(value)
            sub = build(node[2], full=False)
            i = 0
            while len(over) <= node[3]:
                over["k%d" % i] = sub; i += 1
            cases.append(Case("%s %d entries" % (here, len(over)), "set", path, over) if path else None)
        if kind == "set":
            for nk in ("wall_loops", "post_process", "Post_Process", "filament_start_gcode", "machine_end_gcode",
                       "A" * MB):
                cases.append(Case("%s key %s" % (here, nk[:40]), "add", path, "1", where=path, newkey=nk))
            other = "process" if node[1] == "filament" else "filament"
            nk = sorted(R.RULES[other])[0]
            cases.append(Case("%s wrong-block key %s" % (here, nk), "add", path, "1", where=path, newkey=nk))
        if kind == "list":
            sub = build(node[1], full=False)
            over = list(value) + [sub] * (node[2] + 1 - len(value))
            cases.append(Case("%s %d entries" % (here, len(over)), "set", path, over) if path else None)
    return [c for c in cases if c is not None]


class InProcess(fx.TempDir):
    def call(self, fn, *args):
        """(exit code, stdout, stderr, seconds) of fn(*args) with output captured."""
        out, err = io.StringIO(), io.StringIO()
        t = time.perf_counter()
        code = 0
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            try:
                fn(*args)
            except SystemExit as e:
                code = e.code
        dt = time.perf_counter() - t
        if isinstance(code, str):
            err.write(code + "\n"); code = 1
        return code or 0, out.getvalue(), err.getvalue(), dt

    def main(self, *args):
        old = sys.argv
        sys.argv = ["registry.py", "--registry", self.path("filaments.json")] + list(args)
        try:
            return self.call(registry.main)
        finally:
            sys.argv = old

    def commit(self, doc):
        registry.REG = self.path("filaments.json")
        return self.call(registry.commit, doc, True)



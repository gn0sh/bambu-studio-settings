class TileCommand(InProcess):
    """skill-guidance/openscad-define-from-registry: the agent wrote `-D 'FIL="..."'` itself, and a quote in the
    value broke it. registry.py tile prints the whole openscad command, each argument shlex-quoted, from values
    that must match the schema's CODE / PRINTER patterns; no registry is needed."""
    def tile(self, *args):
        return self.main("tile", *args)

    def test_command_splits_to_the_exact_argv(self):
        import os, shlex
        scad = os.path.join(fx.SKILL, "assets", "tile.scad")
        for args, defines, out in ((("PLA-NAVY-01", "--printer", "P1S"), ['PRINTER="P1S"', 'FIL="PLA-NAVY-01"'], "tile.stl"),
                                   (("pla-navy-01",), ['FIL="PLA-NAVY-01"'], "tile.stl"),
                                   (("--printer", "X1C_2", "--layer", "0.16", "--out", "my tile.stl"),
                                    ['PRINTER="X1C_2"', 'LAYER="0.16"'], "my tile.stl"),
                                   ((), [], "tile.stl")):
            with self.subTest(args):
                code, outp, err, dt = self.tile(*args)
                self.assertEqual(code, 0, err)
                want = ["openscad", "-o", out] + [x for d in defines for x in ("-D", d)] + [scad]
                self.assertEqual(shlex.split(outp), want)

    def test_hostile_values_refused(self):
        for ch in SHELL_CHARS + [" ", "\x1b"]:
            for args in (("PLA-NAVY-01" + ch,), ("PLA" + ch + "-NAVY-01",), ("--printer", "P1S" + ch),
                         ("--layer", "0.2" + ch), ("--out", "tile" + ch + ".stl")):
                if args[0] == "--out" and ch == " ":
                    continue                                           # a space in a file name is fine (quoted)
                with self.subTest(args):
                    code, outp, err, dt = self.tile(*args)
                    self.assertEqual((code, outp), (1, ""), args)
                    self.assertNotIn("Traceback", err)
                    self.assertNotIn("\x1b", err)
        for args in (("--printer", "-P1S"), ("--layer", "-0.2"), ("--layer", "5"), ("--out", "-o.stl"),
                     ("--out", "tile.scad"), ("--printer", ""), ("PLA",)):
            with self.subTest(args):
                code, outp, err, dt = self.tile(*args)                 # argparse itself refuses some (exit 2)
                self.assertNotEqual(code, 0, args)
                self.assertEqual(outp, "")

    def test_skill_md_uses_the_command(self):
        text = fx.text("SKILL.md")
        self.assertNotIn("-D '", text)
        self.assertIn("registry.py tile", text)
        self.assertNotIn("-D '", fx.text("references", "tile-spec.md"))


class OneSchema(unittest.TestCase):
    def source(self):
        text = fx.text("scripts", "registry.py")
        a = text.index("# " + "=" * 68 + " SCHEMA (begin)")
        b = text.index("# " + "=" * 68 + " SCHEMA (end)")
        return text[:a] + text[b:]

    def test_no_pattern_or_bound_outside_schema(self):
        outside = self.source()
        compiles = [l.strip() for l in outside.splitlines() if "re.compile(" in l]
        self.assertEqual(len(compiles), 1, compiles)
        self.assertIn("id numbering", compiles[0])
        self.assertEqual(re.findall(r"^\s*MAX_\w+\s*=", outside, re.M), [])
        quantifiers = [q for q in re.findall(r"\{[0-9]+,[0-9]+\}", outside)]
        self.assertEqual(quantifiers, ["{2,4}"])                       # the id-numbering regex only
        for name in ("TEXT(", "PAT(", "LIST(", "MAP(", "OBJ(", "INT(", "NUM(", "PCT("):
            self.assertNotIn(" " + name, outside.replace("def " + name, ""), name)

    def test_retired_checks_are_gone(self):
        for name in ("shape_problems", "setting_problems", "changed_problems", "long_strings", "length_problems",
                     "FIELD_CHARS", "VALUE_RE"):
            self.assertFalse(hasattr(registry, name), name)

    def test_registry_md_lists_every_range(self):
        doc = fx.text("references", "registry.md")
        rows = dict(re.findall(r"^\| `([a-z0-9_]+)` \| (?:filament|process) \| (.+?) \|$", doc, re.M))
        want = {k: R.rule_text(r) for rules in R.RULES.values() for k, r in rules.items()}
        self.assertEqual(rows, want)
        blocks = dict(re.findall(r"^\| `([a-z0-9_]+)` \| (filament|process) \|", doc, re.M))
        self.assertEqual(blocks, {k: b for b, rules in R.RULES.items() for k in rules})


def get_at(doc, path):
    for k in path:
        doc = doc[k]
    return doc


def set_at(doc, path, v):
    get_at(doc, path[:-1])[path[-1]] = v


class PlateField(unittest.TestCase):
    """registry-trust/plate-names: a printer's plate and a test's plate are one of Bambu Studio's plate names, and
    nothing else: no near miss, case change, shell character, leading '-', padding or non-string."""

    def test_only_the_plate_names(self):
        doc = build(R.SCHEMA)
        where = [("printers", "P1S", "plate"), ("filaments", 0, "tests", 0, "plate")]
        for path in where:
            self.assertIn(get_at(doc, path), R.PLATE_NAMES)
            for name in R.PLATE_NAMES:
                with self.subTest(path=path, ok=name):
                    d = build(R.SCHEMA); set_at(d, path, name)
                    self.assertEqual(R.check(d), [])
            bad = ["Textured PEI", "textured pei plate", "TEXTURED PEI PLATE", " Cool Plate", "Cool Plate ",
                   "-Cool Plate", "", "Default Plate", "Cool Plate\x00", "Cool\u202ePlate", "A" * 101]
            bad += ["Cool Plate" + ch for ch in SHELL_CHARS] + [1, 1.5, True, None, ["Cool Plate"], {"a": 1}]
            for v in bad:
                with self.subTest(path=path, bad=repr(v)[:40]):
                    d = build(R.SCHEMA); set_at(d, path, v)
                    problems = R.check(d)
                    self.assertEqual(len(problems), 1, problems)
                    self.assertTrue(problems[0].startswith(ptext(path) + ": "), problems)

    def test_test_plate_is_optional(self):
        d = build(R.SCHEMA)
